    """Ubacuje COMPLEMENTS u values postojećih STRINGS_SEED stavki (in-place)."""
    by_key = {item["key"]: item for item in strings_seed}
    for key, langs in COMPLEMENTS.items():
        item = by_key.get(key)
        if not item:
            strings_seed.append(
                {
                    "key": key,
                    "category": key.split(".", 1)[0] if "." in key else "ui",
                    "description": key,
                    "values": dict(langs),
                }
            )
            continue
        values = item.setdefault("values", {})
        for lang, text in langs.items():
            values.setdefault(lang, text)
