def ensure_translations(db: Session) -> int:
    """Upisuje / ažurira seed ključeve i prevode. Vraća broj upsertovanih prevoda."""
    ensure_languages(db)
    count = 0
    for item in STRINGS_SEED:
        key_row = db.get(TranslationKey, item["key"])
        if not key_row:
            key_row = TranslationKey(
                key=item["key"],
                category=item.get("category") or "ui",
                description=item.get("description"),
            )
            db.add(key_row)
            db.flush()
        else:
            key_row.category = item.get("category") or key_row.category
            key_row.description = item.get("description") or key_row.description

        force = item["key"] in _FORCE_SEED_KEYS
        for lang_code, value in (item.get("values") or {}).items():
            if not db.get(Language, lang_code):
                continue
            existing = (
                db.query(Translation)
                .filter(Translation.key == item["key"], Translation.language_code == lang_code)
                .first()
            )
            if existing:
                if force and existing.value != value:
                    existing.value = value
                    count += 1
                # Inače ne prepisuj ručne izmjene iz /admin/prevodi
                continue
            db.add(Translation(key=item["key"], language_code=lang_code, value=value))
            count += 1
    db.flush()
    return count


def list_languages(db: Session, *, active_only: bool = True) -> list[tuple[str, str]]:
    q = db.query(Language)
    if active_only:
        q = q.filter(Language.active.is_(True))
    rows = q.order_by(Language.sort_order, Language.code).all()
    if not rows:
        return [(x["code"], x["native_name"] or x["name"]) for x in LANGUAGES_SEED]
    return [(r.code, (r.native_name or r.name)) for r in rows]


def get_translations_map(db: Session, language_code: str) -> dict[str, str]:
    """Dict key -> value za jezik; fallback na cnr pa na key."""
    code = language_code or "cnr"
    rows = (
        db.query(Translation)
        .filter(Translation.language_code.in_([code, "cnr"]))
        .all()
    )
    fallback: dict[str, str] = {}
    primary: dict[str, str] = {}
    for row in rows:
        if row.language_code == "cnr":
            fallback[row.key] = row.value
        if row.language_code == code:
            primary[row.key] = row.value
    out = dict(fallback)
    out.update(primary)
    return out


def t(bundle: dict[str, str], key: str, default: str | None = None) -> str:
    return bundle.get(key) or default or key


def upsert_translation(db: Session, key: str, language_code: str, value: str) -> Translation:
    row = (
        db.query(Translation)
        .filter(Translation.key == key, Translation.language_code == language_code)
        .first()
    )
    if row:
        row.value = value
        return row
    row = Translation(key=key, language_code=language_code, value=value)
    db.add(row)
    return row


def export_language_map(db: Session, language_code: str) -> dict[str, str]:
    rows = (
        db.query(Translation)
        .filter(Translation.language_code == language_code)
        .order_by(Translation.key)
        .all()
    )
    return {r.key: r.value for r in rows}


def import_language_map(
    db: Session,
    language_code: str,
    mapping: dict[str, str],
    *,
    create_missing_keys: bool = True,
) -> int:
    """Upsert prevoda. Vraća broj upisanih/izmijenjenih redova."""
    if not db.get(Language, language_code):
        return 0
    count = 0
    for raw_key, raw_val in mapping.items():
        key = (raw_key or "").strip()
        if not key:
            continue
        value = raw_val if isinstance(raw_val, str) else str(raw_val)
        key_row = db.get(TranslationKey, key)
        if not key_row:
            if not create_missing_keys:
                continue
            db.add(TranslationKey(key=key, category="import", description=""))
            db.flush()
        upsert_translation(db, key, language_code, value)
        count += 1
    db.flush()
    return count
