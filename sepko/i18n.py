def ensure_languages(db: Session) -> list[Language]:
    rows: list[Language] = []
    for item in LANGUAGES_SEED:
        row = db.get(Language, item["code"])
        if not row:
            row = Language(**item, active=True)
            db.add(row)
        else:
            row.name = item["name"]
            row.native_name = item["native_name"]
            row.script = item["script"]
            row.is_default = item["is_default"]
            row.sort_order = item["sort_order"]
            row.active = True
        rows.append(row)
    db.flush()
    return rows


